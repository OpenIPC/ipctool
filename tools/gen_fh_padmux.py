#!/usr/bin/env python3
"""Turn Fullhan vendor kernels' pad tables into src/hal/fh_padmux.h.

Fullhan muxes per pad, the HiSilicon way: every pad has one register in the
PMU block, at 0xF0000080 + 4 * pad, and bits 24..27 of it (`mfs` in the
vendor's PinCtrl_Register) select which of the pad's functions it carries.
The vendor kernel lists those functions in its iopad.h as

    PINCTRL_FUNC(SSI0_D2, 46, FUNC0, PUPD_NONE, 4);
    PINCTRL_FUNC(GPIO9,   46, FUNC1, PUPD_NONE, 2);

-- name, pad, selector, pull, drive -- and that is all this script reads. The
pull and drive columns are the vendor's defaults for a function, not part of
selecting it, and are dropped.

Usage:
    gen_fh_padmux.py --table V200=<iopad.h>[,<iopad.h>...] \\
                     --table V100=<iopad.h>[,...] > src/hal/fh_padmux.h
    gen_fh_padmux.py ... --verify src/hal/fh_padmux.h

Several files under one tag must parse to the SAME rows -- the script proves
that the chips sharing a table really do, rather than assuming it from their
names -- and the tag becomes the table's name in C. src/hal/fh_padmux.c maps
chips to tags.

The script refuses rather than guesses: a pad given the same selector twice,
a selector that does not fit the four-bit field, a pad with two GPIO
functions, a GPIO number claimed by two pads, or files under one tag that
disagree all exit non-zero.
"""

import argparse
import hashlib
import os
import re
import sys

PAD_BASE = 0xF0000080
SEL_BITS = 4

ROW = re.compile(
    r"^\s*PINCTRL_FUNC\(\s*(\w+)\s*,\s*(\d+)\s*,\s*FUNC(\d+)\s*,", re.M)
GPIO = re.compile(r"GPIO(\d+)")


class Refusal(Exception):
    pass


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def pmx(name):
    """The PMX_ identifier for a name; tools/gen_padmux_names.py mangles the
    same way, and a disagreement is a compile error rather than a wrong
    name."""
    ident = re.sub(r"[^A-Za-z0-9_]", "__", name)
    if not ident or ident[0].isdigit():
        ident = "_" + ident
    return "PMX_" + ident


def parse(path):
    """Rows (pad, sel, name), sorted by pad then selector, after checking
    everything the backend relies on."""
    with open(path, encoding="utf-8", errors="replace") as handle:
        text = strip_comments(handle.read())
    if re.search(r"^\s*#\s*if", text, re.M):
        # Conditional rows would make the table depend on a kernel config this
        # script cannot see.
        raise Refusal("%s: has #if blocks" % path)

    rows = []
    seen = {}
    gpio_of_pad = {}
    pad_of_gpio = {}
    for name, pad, sel in ROW.findall(text):
        pad, sel = int(pad), int(sel)
        if sel >= 1 << SEL_BITS:
            raise Refusal("%s: %s on pad %d has selector %d, wider than the "
                          "field" % (path, name, pad, sel))
        if (pad, sel) in seen:
            raise Refusal("%s: pad %d selector %d is both %s and %s"
                          % (path, pad, sel, seen[(pad, sel)], name))
        seen[(pad, sel)] = name
        m = GPIO.fullmatch(name)
        if m:
            gpio = int(m.group(1))
            if pad in gpio_of_pad:
                raise Refusal("%s: pad %d is both GPIO%d and GPIO%d"
                              % (path, pad, gpio_of_pad[pad], gpio))
            if gpio in pad_of_gpio:
                raise Refusal("%s: GPIO%d is on pads %d and %d"
                              % (path, gpio, pad_of_gpio[gpio], pad))
            gpio_of_pad[pad] = gpio
            pad_of_gpio[gpio] = pad
        rows.append((pad, sel, name))
    if not rows:
        raise Refusal("%s: no PINCTRL_FUNC rows" % path)
    rows.sort()
    return rows, gpio_of_pad


def digest(path):
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()[:16]


def emit(tables, sources):
    out = []
    w = out.append
    w("/* Generated by tools/gen_fh_padmux.py -- do not edit.")
    w(" *")
    w(" * Fullhan pad functions, one row per (pad, selector), from the vendor")
    w(" * kernel's iopad.h. A pad's register is 0x%08X + 4 * pad and the"
      % PAD_BASE)
    w(" * selector is its bits 24..27; see src/hal/fh_padmux.c.")
    w(" *")
    w(" * Regenerate with:")
    args = " \\\n *       ".join(
        "--table %s=%s" % (tag, ",".join(paths))
        for tag, paths in sources)
    w(" *   tools/gen_fh_padmux.py \\")
    w(" *       %s" % args)
    w(" *")
    w(" * From OpenIPC/linux, as <branch>@<commit>/<path>:")
    for tag, paths in sources:
        for p in paths:
            w(" *   %s  %s" % (digest(p), p))
    w(" */")
    w("")
    w("#ifndef HAL_FH_PADMUX_H")
    w("#define HAL_FH_PADMUX_H")
    w("")
    w('#include "hal/fh_padmux_types.h"')
    for tag, (rows, gpio_of_pad) in tables:
        pads = len({p for p, _, _ in rows})
        w("")
        w("/* %s: %d pads, %d functions, %d of the pads a GPIO. */"
          % (tag, pads, len(rows), len(gpio_of_pad)))
        w("static const fh_func_t FH_%s_funcs[] = {" % tag)
        for pad, sel, name in rows:
            w("    {%d, %d, %d, %s}," % (pad, sel, gpio_of_pad.get(pad, -1),
                                         pmx(name)))
        w("};")
    w("")
    w("#endif /* HAL_FH_PADMUX_H */")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--table", action="append", required=True,
                    metavar="TAG=FILE[,FILE...]")
    ap.add_argument("--verify", metavar="HEADER",
                    help="exit 1 if HEADER is not what this would write")
    opts = ap.parse_args()

    tables, sources = [], []
    try:
        for spec in opts.table:
            tag, _, files = spec.partition("=")
            if not re.fullmatch(r"[A-Z0-9_]+", tag) or not files:
                raise Refusal("--table %r: want TAG=FILE[,FILE...]" % spec)
            paths = files.split(",")
            first = parse(paths[0])
            for p in paths[1:]:
                if parse(p)[0] != first[0]:
                    raise Refusal("%s and %s disagree; give them separate "
                                  "tags" % (paths[0], p))
            tables.append((tag, first))
            sources.append((tag, paths))
    except (Refusal, OSError) as err:
        print("gen_fh_padmux: %s" % err, file=sys.stderr)
        return 2

    text = emit(tables, sources)
    if opts.verify:
        with open(opts.verify, encoding="utf-8") as handle:
            if handle.read() != text:
                print("gen_fh_padmux: %s is stale" % opts.verify,
                      file=sys.stderr)
                return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
